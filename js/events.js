/** Ссылка на точку площадки в Яндекс Картах. */
function yandexMapUrl(event) {
  const [lat, lon] = event.coords;
  const query = encodeURIComponent(event.address);
  return `https://yandex.ru/maps/?ll=${lon}%2C${lat}&z=17&text=${query}`;
}

/** Маршрут до площадки от текущего местоположения. */
function yandexRouteUrl(event) {
  const [lat, lon] = event.coords;
  return `https://yandex.ru/maps/?rtext=~${lat}%2C${lon}&rtt=auto`;
}

/** Статичная карта с меткой — без рекламы и лишних запросов. */
function yandexStaticMapUrl(event, width = 650, height = 420, zoom = 16) {
  const [lat, lon] = event.coords;
  return `https://static-maps.yandex.ru/1.x/?ll=${lon},${lat}&z=${zoom}&l=map&pt=${lon},${lat},pm2blm&size=${width},${height}&lang=ru_RU`;
}
